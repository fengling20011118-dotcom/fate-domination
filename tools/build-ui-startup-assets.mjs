import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const imageExtensions = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif']);
const audioExtensions = new Set(['.mp3', '.ogg', '.wav', '.m4a', '.aac', '.flac']);
const imageDirectories = [
  'assets/map',
  'assets/ui/home-backgrounds',
  'assets/ui/splash-backgrounds',
  'assets/ui/battle-backgrounds'
];

async function collect(directory, extensions) {
  const absolute = path.join(root, directory);
  const found = [];
  async function visit(current) {
    let entries = [];
    try {
      entries = await readdir(current, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      const target = path.join(current, entry.name);
      if (entry.isDirectory()) await visit(target);
      else if (extensions.has(path.extname(entry.name).toLowerCase())) found.push(target);
    }
  }
  await visit(absolute);
  return found;
}

function toPreviewUrl(absolute) {
  const relative = path.relative(root, absolute).split(path.sep).join('/');
  return `../${relative}`;
}

const images = (await Promise.all(imageDirectories.map(directory => collect(directory, imageExtensions))))
  .flat()
  .map(toPreviewUrl);
const audio = (await collect('assets/audio', audioExtensions)).map(toPreviewUrl);
images.sort((a, b) => a.localeCompare(b, 'zh-CN'));
audio.sort((a, b) => a.localeCompare(b, 'zh-CN'));

const source = `// Generated by npm run index:ui-assets.\nwindow.FDStartupAssets = ${JSON.stringify({ images, audio }, null, 2)};\n`;
await writeFile(path.join(root, 'ui-preview', 'startup-assets.js'), source, 'utf8');
console.log(`启动资源清单已生成：${images.length} 张图片，${audio.length} 个音频。`);
